"""Render the site's Manim videos and regenerate data/videos.js.

    <venv>/bin/python manim/render.py              # every scene
    <venv>/bin/python manim/render.py eigen gd     # only these IDs
    <venv>/bin/python manim/render.py --index      # only rebuild data/videos.js from manim/timings
    <venv>/bin/python manim/render.py gd --no-index # render without touching data/videos.js (parallel jobs)

The venv is the one the RL course already set up:
    /Users/ywbw/unimelboure_course/90054_ai_forplaning/map/rl_visual_course/manim/.venv
Output: media/anim/<ID>.mp4 (720p30) and media/anim/<ID>.jpg (poster = last frame).
"""
import glob
import importlib.util
import inspect
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from common import StepScene, TIMINGS  # noqa: E402

OUT = os.path.join(SITE, 'media', 'anim')


def scene_classes():
    found = {}
    for path in sorted(glob.glob(os.path.join(HERE, 'scenes_*.py'))):
        name = os.path.splitext(os.path.basename(path))[0]
        spec = importlib.util.spec_from_file_location(name, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        for _, cls in inspect.getmembers(mod, inspect.isclass):
            if issubclass(cls, StepScene) and cls is not StepScene and getattr(cls, 'ID', None):
                if cls.ID in found and found[cls.ID] is not cls:
                    raise SystemExit('duplicate scene ID ' + cls.ID)
                found[cls.ID] = cls
    return found


def render(cls):
    from manim import tempconfig
    tmp = tempfile.mkdtemp(prefix='smlmanim-')
    with tempconfig({'quality': 'medium_quality', 'media_dir': tmp, 'disable_caching': True,
                     'output_file': cls.ID, 'verbosity': 'WARNING', 'progress_bar': 'none'}):
        scene = cls()
        scene.render()
        mp4 = str(scene.renderer.file_writer.movie_file_path)
    os.makedirs(OUT, exist_ok=True)
    dst = os.path.join(OUT, cls.ID + '.mp4')
    # +faststart moves the index to the front so a browser can start playing (and seek) before the download ends
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', mp4, '-c', 'copy', '-movflags', '+faststart', dst], check=True)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-sseof', '-0.1', '-i', dst, '-frames:v', '1',
                    '-q:v', '4', os.path.join(OUT, cls.ID + '.jpg')], check=True)
    shutil.rmtree(tmp, ignore_errors=True)
    print('rendered', cls.ID, os.path.getsize(dst) // 1024, 'KB')


def build_index():
    vids = {}
    for path in sorted(glob.glob(os.path.join(TIMINGS, '*.json'))):
        with open(path, encoding='utf-8') as f:
            d = json.load(f)
        if not os.path.exists(os.path.join(OUT, d['id'] + '.mp4')):
            continue
        vids[d['id']] = {'title': d['title'], 'src': 'media/anim/' + d['id'] + '.mp4',
                         'poster': 'media/anim/' + d['id'] + '.jpg', 'dur': d['dur'], 'steps': d['steps']}
    js = ('/* Generated by manim/render.py — do not edit by hand. Manim videos with step start times. */\n'
          '(function (root) {\n  root.SML.videos = ' + json.dumps(vids, ensure_ascii=False, indent=1) + ';\n})(window);\n')
    with open(os.path.join(SITE, 'data', 'videos.js'), 'w', encoding='utf-8') as f:
        f.write(js)
    print('data/videos.js:', len(vids), 'videos')


if __name__ == '__main__':
    args = sys.argv[1:]
    no_index = '--no-index' in args          # parallel renders: skip data/videos.js, run --index once at the end
    args = [a for a in args if a != '--no-index']
    if args != ['--index']:
        classes = scene_classes()
        todo = args or sorted(classes)
        missing = [i for i in todo if i not in classes]
        if missing:
            raise SystemExit('unknown scene IDs: ' + ', '.join(missing))
        for i in todo:
            render(classes[i])
    if not no_index:
        build_index()
